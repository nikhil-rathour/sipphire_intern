# 1. Variables - A variable is a name used to store data.

name = "Nikhil"
age = 21
salary = 25000

print(f"name = {name}")
print(f"age = {age}")
print(f"salary = {salary}")


# 2. Data Types - Data type tells Python what kind of data you are storing.

# Integer - Whole numbers

age = 21
marks = 85

print(f"age = {age}")
print(f"marks = {marks}")


# Float - Decimal numbers

height = 5.8
price = 99.50

print(f"height = {height}")
print(f"price = {price}")


# String - Text or characters

name = "Nikhil"
city = "Ahmedabad"

print(f"name = {name}")
print(f"city = {city}")


# Boolean - True or False values

is_student = True
is_logged_in = False

print(f"is_student = {is_student}")
print(f"is_logged_in = {is_logged_in}")


# List - Stores multiple values in a single variable

fruits = ["Apple", "Mango", "Banana"]

print(f"fruits = {fruits}")


# Tuple - Stores multiple values that cannot normally be changed

colors = ("Red", "Blue", "Green")

print(f"colors = {colors}")


# Set - Stores unique values

numbers = {10, 20, 30, 40}

print(f"numbers = {numbers}")


# Dictionary - Stores data in key-value pairs

student = {
    "name": "Nikhil",
    "age": 21,
    "course": "Python",
    "marks": 85
}

print(f"student = {student}")


# Complex - Stores complex numbers with real and imaginary parts

number = 3 + 4j

print(f"number = {number}")


# Range - Represents a sequence of numbers

numbers = range(1, 6)
print(f"numbers = {list(numbers)}")


# NoneType - Represents no value or absence of a value

result = None

print(f"result = {result}")


# Check Data Type - type() is used to check the data type of a variable

name = "Nikhil"
age = 21
height = 5.8
is_student = True

print(f"type of name = {type(name)}")
print(f"type of age = {type(age)}")
print(f"type of height = {type(height)}")
print(f"type of is_student = {type(is_student)}")



